     function initAlbumDetail(artistId) {
    const detail = document.getElementById("album-detail");
    const songList = document.getElementById("song-list");

    if (!detail || !songList) {
        console.error("Không tìm thấy album-detail hoặc song-list");
        return;
    }

    const artist = database[artistId];

    if (!artist) {
        console.error("Không tìm thấy artist:", artistId);
        detail.innerHTML = `
            <p class="text-gray-400">
                Không tìm thấy thông tin nghệ sĩ.
            </p>
        `;
        songList.innerHTML = "";
        return;
    }

    // ==========================
    // 1. THÔNG TIN ALBUM
    // ==========================
    const cover = document.getElementById("album-cover");
    const title = document.getElementById("album-title");
    const artistName = document.getElementById("artist-header-name");
    const genre = document.getElementById("album-genre");

    if (cover) {
        cover.src = artist.cover;
        cover.alt = artist.album;
        cover.onerror = function () {
            this.src = "./images/default-album.jpg";
        };
    }

    if (title) title.textContent = artist.album;
    if (artistName) artistName.textContent = artist.name;
    if (genre) genre.textContent = `${artist.genre} • ${artist.year}`;

    // ==========================
    // 2. DANH SÁCH BÀI HÁT (TỐI ƯU DOM)
    // ==========================
    let songsHTML = "";

    artist.songs.forEach((song, index) => {
        const songTitle = typeof song === "string" ? song : song.title;
        const songImg = typeof song === "string" ? artist.cover : (song.img || artist.cover);
        const duration = `3:${String((index * 7 + 12) % 60).padStart(2, "0")}`;

        songsHTML += `
            <tr class="hover:bg-white/10 cursor-pointer transition group song-row" data-index="${index}">
                <!-- STT -->
                <td class="py-3 pl-4 w-12 text-center text-gray-500 group-hover:text-[#a39aff]">
                    ${index + 1}
                </td>

                <!-- BÀI HÁT -->
                <td class="py-3 pl-4">
                    <div class="flex items-center gap-4">
                        <img
                            src="${songImg}"
                            alt="${songTitle}"
                            class="w-12 h-12 object-cover rounded-md flex-shrink-0"
                            onerror="this.src='./images/default-album.jpg'"
                        >
                        <div class="min-w-0">
                            <p class="text-white font-medium group-hover:text-[#a39aff] transition truncate">
                                ${songTitle}
                            </p>
                            <p class="text-gray-500 text-sm truncate">
                                ${artist.name}
                            </p>
                        </div>
                    </div>
                </td>

                <!-- THỜI LƯỢNG -->
                <td class="py-3 pr-4 text-right w-20 text-gray-500 text-sm">
                    ${duration}
                </td>
            </tr>
        `;
    });

    // Gán HTML 1 lần duy nhất
    songList.innerHTML = songsHTML;

    // Gán sự kiện click cho từng dòng bài hát
    const rows = songList.querySelectorAll(".song-row");
    rows.forEach((row) => {
        row.addEventListener("click", () => {
            const index = parseInt(row.getAttribute("data-index"), 10);
            playTrack(artistId, index);
        });
    });

    // ==========================
    // 3. NÚT PHÁT TẤT CẢ
    // ==========================
    const playAllBtn = document.getElementById("play-all");
    if (playAllBtn) {
        playAllBtn.onclick = function () {
            if (!artist.songs || artist.songs.length === 0) return;
            playTrack(artistId, 0);
        };
    }

    console.log("Đã load album:", artist.name);
}

